export type TranslationKey = keyof typeof DICTIONARY.tr;

/**
 * Hook to retrieve the current language and translator function.
 */
export function useI18n() {
  const language = useStore((s) => (s.db.settings.language ?? "tr") as Language);
  const dict = DICTIONARY[language] ?? DICTIONARY.tr;

  // Month and weekday names come from date-fns rather than the dictionary, so
  // the two have to be told about a language change together — otherwise the
  // labels switch and the dates stay behind.
  setDateLocale(language);

  /**
   * Look a string up, filling in any `{placeholder}` it carries.
   *
   * Interpolation rather than string concatenation at the call site, because
   * word order is not the same in every language: "3 gün sonra" and "in 3 days"
   * put the number in different places, and only the dictionary can know that.
   */
  const t = (
    key: TranslationKey,
    params?: Record<string, string | number>,
  ): string => {
    const value = (dict as Record<string, string>)[key] ?? key;
    if (!params) return value;
    return value.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in params ? String(params[name]) : whole,
    );
  };

  return { language, t, dict };
}
